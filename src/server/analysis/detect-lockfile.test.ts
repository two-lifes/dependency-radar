import { describe, expect, it } from "vitest";
import { detectLockfile } from "./detect-lockfile";

// Headers are copied verbatim from real lockfiles; the source is noted on each.
// The bodies are cut short because detection only looks at the start.

describe("detectLockfile", () => {
  it.each([
    [
      // npm/cli@v7.24.2 package-lock.json
      "v2",
      '{\n  "name": "npm",\n  "version": "7.24.2",\n  "lockfileVersion": 2,\n  "requires": true,\n  "packages": {}\n}\n',
    ],
    [
      // npm/cli@v8.19.4 package-lock.json
      "v3",
      '{\n  "name": "npm",\n  "version": "8.19.4",\n  "lockfileVersion": 3,\n  "requires": true,\n  "packages": {}\n}\n',
    ],
  ])("recognizes package-lock.json %s", (_label, text) => {
    expect(detectLockfile(text)).toBe("npm");
  });

  it.each([
    // pnpm 9+ (vitejs/vite@main, this repo's own pnpm-lock.yaml)
    [
      "v9 with the --- document marker",
      "---\nlockfileVersion: '9.0'\n\nimporters:\n\n  .:\n",
    ],
    // pnpm 8 (vuejs/core@v3.3.4)
    ["v6", "lockfileVersion: '6.0'\n\nimporters:\n\n  .:\n"],
  ])("recognizes pnpm-lock.yaml %s", (_label, text) => {
    expect(detectLockfile(text)).toBe("pnpm");
  });

  it("recognizes a yarn v1 lockfile", () => {
    // uri-js@4.4.1 yarn.lock
    const text =
      "# THIS IS AN AUTOGENERATED FILE. DO NOT EDIT THIS FILE DIRECTLY.\n# yarn lockfile v1\n\n\n";

    expect(detectLockfile(text)).toBe("yarn");
  });

  it("recognizes a yarn berry lockfile", () => {
    // yarnpkg/berry@master yarn.lock
    const text =
      '# This file is generated by running "yarn install" inside your project.\n# Manual changes might be lost - proceed with caution!\n\n__metadata:\n  version: 10\n  cacheKey: 10\n';

    expect(detectLockfile(text)).toBe("yarn");
  });

  it("recognizes lockfiles saved with CRLF line endings", () => {
    expect(detectLockfile("---\r\nlockfileVersion: '9.0'\r\n")).toBe("pnpm");
  });

  it.each([
    [
      "a package.json",
      '{\n  "dependencies": {\n    "react": "^19.0.0"\n  }\n}\n',
    ],
    ["invalid JSON", '{\n  "dependencies": {\n    react: "^19"\n  }\n}'],
    [
      "truncated package-lock.json",
      '{\n  "name": "npm",\n  "lockfileVersion": 3,\n',
    ],
    ["an empty string", ""],
    [
      "lockfileVersion that is not the first key",
      "name: app\nlockfileVersion: 9\n",
    ],
  ])("returns undefined for %s", (_label, text) => {
    expect(detectLockfile(text)).toBeUndefined();
  });
});
